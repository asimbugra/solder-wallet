"""Packs web/index.html into src/web_ui.h (gzipped byte array).

Fonts and scripts referenced from web/vendor are inlined, so the page works
without internet (phones on Solder's own WiFi may have none).

Runs before every PlatformIO build (extra_scripts) and can be run by hand:
    python3 web/build.py
"""
import base64
import gzip
import hashlib
import os
import re

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
SRC = os.path.join(WEB, "index.html")
OUT = os.path.join(ROOT, "src", "web_ui.h")


def inline(html):
    def font(m):
        path = os.path.join(WEB, m.group(1))
        data = base64.b64encode(open(path, "rb").read()).decode()
        return "url(data:font/woff2;base64,%s)" % data

    def script(m):
        return "<script>\n%s\n</script>" % open(os.path.join(WEB, m.group(1)), encoding="utf8").read()

    html = re.sub(r'url\((vendor/[^)]+\.woff2)\)', font, html)
    html = re.sub(r'<script src="(vendor/[^"]+)"></script>', script, html)
    return html


def build():
    html = inline(open(SRC, encoding="utf8").read())
    hashes = ["'sha256-%s'" % base64.b64encode(hashlib.sha256(script.encode()).digest()).decode()
              for script in re.findall(r"<script>(.*?)</script>", html, re.S)]
    csp = ("default-src 'none'; script-src " + " ".join(hashes) +
           "; style-src 'unsafe-inline'; font-src data:; connect-src 'self' https:; "
           "frame-ancestors 'none'; base-uri 'none'; form-action 'none'")
    gz = gzip.compress(html.encode("utf8"), 9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    header = ("// Generated by web/build.py from web/index.html, do not edit.\n"
              "#pragma once\n#include <Arduino.h>\n\n"
              'static const char WEB_UI_CSP[] = "%s";\n' % csp +
              "static const size_t WEB_UI_GZ_LEN = %d;\n" % len(gz) +
              "static const uint8_t WEB_UI_GZ[] PROGMEM = {\n%s\n};\n" % "\n".join(lines))
    if os.path.exists(OUT):
        with open(OUT) as f:
            if f.read() == header:
                return
    with open(OUT, "w") as f:
        f.write(header)
    print("web/build.py: index.html -> src/web_ui.h (%d bytes gzipped)" % len(gz))


build()
